// קוד פנייה (רותם 7.10.2026, אחרי העסקה הראשונה SC-018: לא ידוע מאיפה הלקוח הגיע, כי קישור wa.me לא נושא gclid/UTM).
// בכל לחיצה על כפתור ווצאפ הדפדפן מוסיף לסוף ההודעה שורה "מס' פנייה: SCW-XXXXXX" ושולח את הקוד עם המקור ל-/api/wa-ref.
// 6 תווים: אותיות גדולות וספרות בלי O/0/I/1 (שלא יתבלבלו כשמקריאים בטלפון).
export const WA_REF_LABEL = "מס' פנייה:";
export const WA_REF_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
export const WA_REF_RE = /\bSCW-[A-HJ-NP-Z2-9]{6}\b/;

/** קוד הפנייה שבתוך הודעה ("SCW-XXXXXX"), או null אם אין */
export function waRefOf(text: string): string | null {
  const m = new RegExp(WA_REF_RE.source, "i").exec(String(text || ""));
  return m ? m[0].toUpperCase() : null;
}

/** ההודעה בלי שורת קוד הפנייה (לפני השוואה לטקסטים של הכפתורים, ולתצוגה) */
export function stripWaRef(text: string): string {
  return String(text || "").replace(new RegExp(`\\s*${WA_REF_LABEL}\\s*${WA_REF_RE.source}`, "gi"), "").trim();
}

/** הודעה נכנסת בצורה אחידה: בלי רווחים/שורות ריקות/סימני כיווניות בהתחלה, עד 3 תווים מיותרים לפני הפתיחה, ופסיק+רווח אחרי "היי"/"שלום" */
function normalize(text: string): string {
  const t = stripWaRef(text).replace(/^[\s‎‏﻿]+/, "");
  const m = /^.{0,3}?(היי|שלום)[\s,]*/.exec(t);
  return m ? `${m[1]}, ${t.slice(m[0].length)}` : t;
}

/** מאיזה מקום באתר הגיעה ההודעה, או null אם זו לא הודעה ממולאת מהאתר */
export function siteSourceOf(text: string): string | null {
  const t = normalize(text);
  for (const [re, label] of PREFILLS) if (re.test(t)) return label;
  // גיבוי: קוד פנייה נוצר רק בלחיצה על כפתור באתר, אז הודעה שיש בה קוד הגיעה מהאתר גם אם הלקוח שינה את הטקסט
  if (waRefOf(text)) return "כפתור ווצאפ באתר (לפי קוד פנייה)";
  return null;
}
