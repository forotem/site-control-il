  <p>הגישה הפסיבית, של הסתמכות על מזל טוב והיעדר אירועים פליליים, היא למעשה חוסר אסטרטגיה מוחלט. היא חושפת אתכם לסיכון כלכלי, תפעולי ומוניטין. כשמתרחש אירוע פלילי, ההשלכות הן לרוב חמורות ויקרות בהרבה מעלות ההשקעה בפתרון אבטחה מתאים.</p>

